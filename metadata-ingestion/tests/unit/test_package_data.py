def _load_package_data() -> Dict[str, List[str]]:
    """Read package_data out of setup.py, which is the source of truth for it."""
    setup_py = METADATA_INGESTION_DIR / "setup.py"
    namespace: Dict = {"__name__": "__not_main__", "__file__": str(setup_py)}
    code = setup_py.read_text().replace("setuptools.setup(", "_setup_args = dict(")
    exec(code, namespace)
    return namespace["_setup_args"]["package_data"]


def _shipped_patterns() -> Set[str]:
    """Expand package_data into POSIX glob patterns relative to src/."""
    # setuptools adds py.typed to every package it builds, declared or not.
    patterns = {"*/py.typed"}
    for package, globs in _load_package_data().items():
        prefix = package.replace(".", "/")
        for glob in globs:
            patterns.add(f"{prefix}/{glob}")
    return patterns


def _matches(rel: str, pattern: str) -> bool:
    """Match a src-relative path against a package_data pattern.

    setuptools evaluates package_data per package, so a `*` never spans a
    directory separator and never reaches into a subpackage: the
    `datahub.ingestion.autogenerated` entry does not cover
    `autogenerated/connector_registry/`. fnmatch on the whole path would let it,
    so compare component by component.
    """
    rel_parts = rel.split("/")
    pattern_parts = pattern.split("/")
    if len(rel_parts) != len(pattern_parts):
        return False
    return all(
        fnmatch.fnmatch(part, pattern_part)
        for part, pattern_part in zip(rel_parts, pattern_parts, strict=True)
    )


def _is_build_artifact(path: pathlib.Path) -> bool:
    """Skip what an editable install leaves behind: src/*.egg-info, caches."""
    return any(
        part == "__pycache__" or part.endswith(".egg-info") for part in path.parts
    )


def _data_files() -> List[str]:
    return sorted(
        path.relative_to(SRC_DIR).as_posix()
        for path in SRC_DIR.rglob("*")
        if path.is_file()
        and path.suffix not in (".py", ".pyc")
        and not _is_build_artifact(path)
    )


def test_data_files_are_shipped_or_exempt() -> None:
    patterns = _shipped_patterns()
    undeclared = [
        rel
        for rel in _data_files()
        if rel not in NOT_SHIPPED
        and not any(_matches(rel, pattern) for pattern in patterns)
    ]
    assert not undeclared, (
        "These files live under src/ but no package_data glob in setup.py matches "
        "them, so they will be absent from the built wheel. Either add a "
        "package_data entry (and re-run scripts/generate_pyproject_deps.py) or "
        f"list them in NOT_SHIPPED with a reason: {undeclared}"
    )


def test_not_shipped_entries_still_exist() -> None:
    """Keep NOT_SHIPPED from rotting into a list of deleted paths."""
    stale = [rel for rel in NOT_SHIPPED if not (SRC_DIR / rel).exists()]
    assert not stale, f"NOT_SHIPPED lists paths that no longer exist: {stale}"


def test_not_shipped_entries_are_not_also_declared() -> None:
    """A file cannot be both exempt and shipped; that means one is wrong."""
    patterns = _shipped_patterns()
    contradictory = [
        rel
        for rel in NOT_SHIPPED
        if any(_matches(rel, pattern) for pattern in patterns)
    ]
    assert not contradictory, (
        f"Listed in NOT_SHIPPED but matched by a package_data glob: {contradictory}"
    )
