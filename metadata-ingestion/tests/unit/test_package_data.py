"""Guard that non-Python files under src/ are either shipped or explicitly exempt.

Every other test imports `datahub` from the source tree, where data files are
present whether or not `package_data` mentions them. A missing `package_data`
entry therefore cannot fail any normal test -- it only surfaces as a
FileNotFoundError for users of the published wheel. This test checks the
declaration instead of the checkout, so the gap is closed at review time.

The check is fail-closed: a new non-Python file under src/ must either match a
`package_data` glob or be added to `NOT_SHIPPED` with a reason. That forces the
ship/don't-ship decision to be made once, explicitly.
"""

