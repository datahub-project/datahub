"""Guards that every ingestion connector has a tile in the UI's ingestion source
builder, so a new connector isn't left reachable only through the "Custom"
recipe option.

The UI catalog is a static file, ``sources.json``, separate from the connector
code. Connectors such as IBM Db2 shipped without a tile because nothing linked
the two. This test fails when a *new* connector is added to the autogenerated
connector registry without either a tile or an explicit exemption below.

The only hard-coded input is ``_NOT_UI_SOURCES``: sources that should never get
a tile of their own. Keep it small.

This test runs with the metadata-ingestion tests, so it catches new connectors
but not edits that only touch ``sources.json``.
"""

import json
from pathlib import Path
from typing import Set

import pytest
import yaml

from datahub.ingestion.source.source_registry import source_registry

_HERE = Path(__file__).resolve()
_METADATA_INGESTION_DIR = _HERE.parents[2]
_REPO_ROOT = _HERE.parents[3]

_CONNECTOR_REGISTRY = (
    _METADATA_INGESTION_DIR
    / "src/datahub/ingestion/autogenerated/connector_registry/datahub.json"
)
_UI_SOURCES = (
    _REPO_ROOT / "datahub-web-react/src/app/ingestV2/source/builder/sources.json"
)

_NOT_UI_SOURCES: Set[str] = {
    # DataHub-internal, utility or file-based sources.
    "datahub",
    "datahub-apply",
    "datahub-business-glossary",
    "datahub-debug",
    "datahub-documents",
    "datahub-gc",
    "datahub-lineage-file",
    "demo-data",
    "file",
    "json-schema",
    # Generic sources whose platform is set per recipe; use the Custom tile.
    "sql-queries",
    "sqlalchemy",
    # Usage-only variants of connectors whose tile covers usage.
    "clickhouse-usage",
    "starburst-trino-usage",
    # Deprecated alias of hive-metastore.
    "presto-on-hive",
    # Reads dlt's local pipeline state directory; there is no remote storage option.
    "dlt",
}


def _registry_source_types() -> Set[str]:
    if not _CONNECTOR_REGISTRY.exists():
        pytest.skip(f"connector registry not present: {_CONNECTOR_REGISTRY}")
    return set(json.loads(_CONNECTOR_REGISTRY.read_text())["plugin_details"])


def _tile_source_types() -> Set[str]:
    if not _UI_SOURCES.exists():
        pytest.skip(f"UI source catalog not present in this checkout: {_UI_SOURCES}")
    types: Set[str] = set()
    for tile in json.loads(_UI_SOURCES.read_text()):
        recipe = yaml.safe_load(tile.get("recipe") or "") or {}
        source_type = recipe.get("source", {}).get("type")
        if source_type:
            types.add(source_type)
            # A tile may use an alias, e.g. `databricks` for `unity-catalog`. Count
            # both: `hive-metastore` is a registry key and an alias of
            # `presto-on-hive`.
            alias_target = source_registry.get_alias_target(source_type)
            if alias_target:
                types.add(alias_target)
    return types


def test_every_connector_has_a_ui_tile() -> None:
    missing = sorted(_registry_source_types() - _tile_source_types() - _NOT_UI_SOURCES)
    assert not missing, (
        f"{len(missing)} connector(s) have no tile in "
        f"{_UI_SOURCES.relative_to(_REPO_ROOT)}: {missing}. Add a tile (urn, name, "
        "displayName, description, docsUrl, recipe, category) and its i18n "
        "description key, or, if the source should never appear in the UI, add it "
        "to _NOT_UI_SOURCES with a reason."
    )


def test_exemptions_name_real_connectors() -> None:
    unknown = sorted(_NOT_UI_SOURCES - _registry_source_types())
    assert not unknown, (
        f"Exempted source types are not in the connector registry: {unknown}. "
        "Remove them from _NOT_UI_SOURCES."
    )
