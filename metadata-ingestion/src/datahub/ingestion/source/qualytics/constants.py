"""Stable identifiers shared across the connector.

Anything here is effectively a contract with DataHub or with already-emitted metadata:
changing a value orphans entities that were emitted under the old one.
"""

import json
import logging
from functools import lru_cache
from importlib import resources
from typing import Final

logger = logging.getLogger(__name__)

# DataHub platform id for Qualytics: the custom-assertion type and the platform in
# every assertion's dataPlatformInstance. Must match the platform registered in
# DataHub's bootstrap_mcps/data-platforms.yaml.
PLATFORM: Final = "qualytics"

# Qualytics' own API root path. It is configured per deployment, so "/api" is the
# default rather than a guarantee.
DEFAULT_API_ROOT_PATH: Final = "/api"

# API paths, relative to the configured `base_url` (which already ends in the root path,
# e.g. https://acme.qualytics.io/api). The spec's own path keys INCLUDE the root path --
# `/api/datastores` there is `/datastores` here -- which is why
# tests/unit/test_api_paths.py joins the two before comparing. Every path in
# CONSUMED_PATHS is verified against tests/unit/qualytics/fixtures/openapi.json by that test. Do
# not add one from memory; read the spec.

# Not in CONSUMED_PATHS: a deployment does not list its own spec among its paths.
OPENAPI_PATH: Final = "/openapi.json"

DATASTORES_PATH: Final = "/datastores"
CONTAINERS_PATH: Final = "/containers"
# Latest profile for a container, and the latest per-field profiles under it.
CONTAINER_PROFILE_PATH: Final = "/containers/{id}/profile"
CONTAINER_FIELD_PROFILES_PATH: Final = "/containers/{id}/field-profiles"
# The collection-level field-profiles endpoint. Only a cheap capability probe in
# test_connection; real profile reads use the per-container path above.
FIELD_PROFILES_PATH: Final = "/field-profiles"
QUALITY_CHECKS_PATH: Final = "/quality-checks"
ANOMALIES_PATH: Final = "/anomalies"

# Paths the client actually requests, and the paths the spec fixture is trimmed to. An
# entry no code calls turns a contract test into decoration; a path we call but omit is
# unguarded.
CONSUMED_PATHS: Final = (
    DATASTORES_PATH,
    CONTAINERS_PATH,
    CONTAINER_PROFILE_PATH,
    CONTAINER_FIELD_PROFILES_PATH,
    FIELD_PROFILES_PATH,
    QUALITY_CHECKS_PATH,
    ANOMALIES_PATH,
)


@lru_cache(maxsize=1)
def get_known_data_platforms() -> frozenset[str] | None:
    """Canonical DataHub platform names, for validating configured platforms.

    Source of truth is the autogenerated connector registry: each entry's
    ``platform_id`` is the platform name that connector puts in its dataset URNs. If a
    user configures a platform outside this set, no source emits URNs under it, so any
    assertion we attach there is invisible.

    Returns None when the registry cannot be read -- some installs strip the
    autogenerated package. Callers must treat that as "validation unavailable" and
    skip, rather than failing every run or silently accepting anything.

    NB: montecarlo and kafka_connect each carry their own copy of this. Duplicating it
    a third time is the wrong shape for a shared concern, but importing across source
    packages is worse; worth proposing a shared utility in the upstream PR.
    """
    try:
        registry = resources.files("datahub.ingestion.autogenerated.connector_registry")
        data = json.loads((registry / "datahub.json").read_text())
        platforms = frozenset(
            info["platform_id"]
            for info in data.get("plugin_details", {}).values()
            if info.get("platform_id")
        )
        if not platforms:
            # Fail open, not closed. If DataHub renames `plugin_details` or
            # `platform_id`, the comprehension yields nothing without raising, and
            # returning an empty set would make _validate_platform_value reject every
            # platform -- breaking datastore_to_platform_map for everyone.
            logger.warning(
                "Qualytics connector: the DataHub connector registry parsed to zero "
                "platforms, so its shape has probably changed. Skipping platform-name "
                "validation rather than rejecting every platform."
            )
            return None
        return platforms
    except Exception as e:
        logger.warning(
            "Qualytics connector: could not load the DataHub connector registry, so "
            "configured platform names will not be validated. Reason: %s",
            e,
        )
        return None
