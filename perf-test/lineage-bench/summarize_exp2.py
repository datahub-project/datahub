#!/usr/bin/env python3
"""Summarise experiment 2: OpenSearch vs in-memory (experiment 1) vs in-memory with the lightning
search pushed down (experiment 2), per start node group and query shape.

Reads the walks.csv files of the three GMS runs (and the server-only runs, when present) and writes
summary.json and summary.md next to them. Medians over every walk of a (family, note) group.
Stdlib only.

  python3 summarize_exp2.py --exp2 results/exp2
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import statistics
from pathlib import Path
from typing import Any, Dict, List, Optional

BACKENDS = {
    "opensearch": "06_bench_opensearch",
    "inmem_full": "05_bench_pushdown_off",
    "inmem_pushdown": "03_bench_pushdown_on",
}
SHAPES = ["ui", "filtered50"]
# Stages of one request, in ms; a stage missing on a backend is left out.
STAGES = {
    "wall_ms": "end to end (client)",
    "gms_walk_ms": "walk step in GMS (incl. server call, transfer, decode, build)",
    "walk_server_walk_ms": "server walk",
    "walk_server_search_ms": "server search (filter, page, facets)",
    "walk_http_ms": "server call (HTTP)",
    "walk_decode_ms": "decode",
    "walk_build_ms": "build results",
    "walk_bytes": "response bytes",
    "search_filter_ms": "GMS filter step",
    "search_result_ms": "GMS result step",
    "resolver_map_ms": "GraphQL mapping",
}
KEY_GROUPS = [
    ("prod_like", "root"), ("wide", "root"), ("mid", "root"), ("deep100_w1k", "root"), ("hub", "root"),
    ("deep", "root"), ("scc", "member"), ("prod_like", "layer1"), ("deep100_w100", "root"),
    ("deep100_w10", "root"), ("deep100_w1", "root"), ("small_islands", "root"),
]


def num(v: Any) -> Optional[float]:
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def load(path: Path) -> List[Dict[str, Any]]:
    return list(csv.DictReader(path.open())) if path.exists() else []


def medians(rows: List[Dict[str, Any]]) -> Dict[tuple, Dict[str, Any]]:
    groups: Dict[tuple, List[Dict[str, Any]]] = {}
    for r in rows:
        groups.setdefault((r["family"], r["note"]), []).append(r)
    out = {}
    for key, rs in groups.items():
        m: Dict[str, Any] = {"n": len(rs), "expected_total": int(rs[0]["expected_total"]),
                             "errors": sum(1 for r in rs if r.get("status") != "ok"),
                             "mismatches": sum(1 for r in rs if str(r.get("total")) != str(r.get("expected_total")))}
        for col in STAGES:
            vals = [num(r.get(col)) for r in rs]
            vals = [v for v in vals if v is not None]
            if vals:
                m[col] = round(statistics.median(vals), 2)
        out[key] = m
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--exp2", type=Path, default=Path(__file__).parent / "results/exp2")
    args = ap.parse_args()

    summary: Dict[str, Any] = {"shapes": {}}
    md: List[str] = ["# Experiment 2 summary (generated by summarize_exp2.py)", ""]
    for shape in SHAPES:
        per_backend = {b: medians(load(args.exp2 / d / f"gms_{shape}" / "walks.csv")) for b, d in BACKENDS.items()}
        groups = sorted(set().union(*[set(v) for v in per_backend.values()]))
        shape_out = {}
        speedups_full, speedups_os = [], []
        for g in groups:
            row = {b: per_backend[b].get(g) for b in BACKENDS}
            shape_out[f"{g[0]}:{g[1]}"] = row
            p, f, o = (row["inmem_pushdown"] or {}), (row["inmem_full"] or {}), (row["opensearch"] or {})
            if p.get("wall_ms") and f.get("wall_ms"):
                speedups_full.append(f["wall_ms"] / max(p["wall_ms"], 1))
            if p.get("wall_ms") and o.get("wall_ms"):
                speedups_os.append(o["wall_ms"] / max(p["wall_ms"], 1))
        geo = lambda xs: round(math.exp(sum(math.log(x) for x in xs) / len(xs)), 2) if xs else None
        summary["shapes"][shape] = {"groups": shape_out, "geomean_speedup_vs_inmem_full": geo(speedups_full),
                                    "geomean_speedup_vs_opensearch": geo(speedups_os)}

        md += [f"## `{shape}`: median end to end through GMS, ms", "",
               "| Start node | Results | OpenSearch | In-memory (exp 1) | Pushdown (exp 2) | vs exp 1 | vs OpenSearch |",
               "|---|---|---|---|---|---|---|"]
        for g in KEY_GROUPS:
            row = shape_out.get(f"{g[0]}:{g[1]}")
            if not row:
                continue
            o, f, p = (row["opensearch"] or {}), (row["inmem_full"] or {}), (row["inmem_pushdown"] or {})
            total = (o or f or p).get("expected_total")
            def fmt(x: Dict[str, Any]) -> str:
                return f"{x['wall_ms']:,.0f}" if x.get("wall_ms") is not None else "–"
            sf = f"{f['wall_ms'] / max(p['wall_ms'], 1):.1f}×" if f.get("wall_ms") and p.get("wall_ms") else "–"
            so = f"{o['wall_ms'] / max(p['wall_ms'], 1):.1f}×" if o.get("wall_ms") and p.get("wall_ms") else "–"
            md.append(f"| {g[0]} {g[1]} | {total:,} | {fmt(o)} | {fmt(f)} | {fmt(p)} | {sf} | {so} |")
        md += ["", f"Geometric mean speedup over all {len(groups)} groups: "
               f"{summary['shapes'][shape]['geomean_speedup_vs_inmem_full']}× vs experiment 1, "
               f"{summary['shapes'][shape]['geomean_speedup_vs_opensearch']}× vs OpenSearch.", ""]

        md += [f"### `{shape}`, prod_like root: where the time goes (median ms)", "",
               "| Stage | OpenSearch | In-memory (exp 1) | Pushdown (exp 2) |", "|---|---|---|---|"]
        root = shape_out.get("prod_like:root", {})
        for col, label in STAGES.items():
            vals = [(root.get(b) or {}).get(col) for b in ("opensearch", "inmem_full", "inmem_pushdown")]
            if any(v is not None for v in vals):
                md.append(f"| {label} | " + " | ".join("–" if v is None else f"{v:,.1f}" for v in vals) + " |")
        md.append("")

    for shape in SHAPES:
        rows = load(args.exp2 / "03_bench_pushdown_on" / f"direct_search_{shape}" / "walks.csv")
        if rows:
            m = medians(rows)
            summary.setdefault("server_only", {})[shape] = {f"{k[0]}:{k[1]}": v for k, v in m.items()}
    direct = load(args.exp2 / "03_bench_pushdown_on" / "direct_walk" / "walks.csv")
    if direct:
        summary["server_only_full_walk"] = {f"{k[0]}:{k[1]}": v for k, v in medians(direct).items()}

    (args.exp2 / "summary.json").write_text(json.dumps(summary, indent=1))
    (args.exp2 / "summary.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
