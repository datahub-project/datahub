import fs from 'fs';
import path from 'path';
import { describe, expect, it } from 'vitest';
import YAML from 'yamljs';

import { RECIPE_FIELDS } from '@app/ingestV2/source/builder/RecipeForm/constants';
import { SOURCE_TYPE_ALIASES } from '@app/ingestV2/source/builder/constants';
import sources from '@app/ingestV2/source/builder/sources.json';

// The Python connector registry, the source of truth for which source types exist.
const registry = JSON.parse(
    fs.readFileSync(
        path.resolve(
            process.cwd(),
            '../metadata-ingestion/src/datahub/ingestion/autogenerated/connector_registry/datahub.json',
        ),
        'utf-8',
    ),
);
const registryTypes = new Set(Object.keys(registry.plugin_details));

function recipeType(recipe: string | undefined): string | undefined {
    return recipe ? YAML.parse(recipe)?.source?.type : undefined;
}

describe('sources.json and the connector registry', () => {
    it('uses a registered source type, or a known alias of one, in every tile recipe', () => {
        const unknown = sources
            .map((source) => ({ name: source.name, type: recipeType(source.recipe) }))
            .filter(({ name, type }) => name !== 'custom' && type !== undefined)
            .filter(({ type }) => !registryTypes.has(type as string) && !(type! in SOURCE_TYPE_ALIASES))
            .map(({ name, type }) => `${name}: ${type}`);

        expect(unknown).toEqual([]);
    });

    it('maps every alias to a registered source type', () => {
        const dangling = Object.entries(SOURCE_TYPE_ALIASES).filter(([, target]) => !registryTypes.has(target));

        expect(dangling).toEqual([]);
    });

    it('only defines structured forms for tiles that exist', () => {
        const tileNames = new Set(sources.map((source) => source.name));

        expect(Object.keys(RECIPE_FIELDS).filter((name) => !tileNames.has(name))).toEqual([]);
    });
});
