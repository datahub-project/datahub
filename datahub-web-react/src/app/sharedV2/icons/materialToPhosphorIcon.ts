const STYLE_SUFFIXES = ['Outlined', 'Rounded', 'Sharp', 'TwoTone', 'Filled'] as const;

function stripMaterialStyleSuffix(name: string): string {
    const suffix = STYLE_SUFFIXES.find((s) => name.endsWith(s) && name.length > s.length);
    return suffix ? name.slice(0, -suffix.length) : name;
}

/**
 * Resolve a stored icon name to a Phosphor component name.
 * Known Material names map to a close Phosphor equivalent; Phosphor names pass through.
 * Material-style names with no synonym fall back to {@link DEFAULT_PHOSPHOR_ICON}.
 */
export function resolvePhosphorIconName(storedName: string | null | undefined): string | null {
    if (!storedName?.trim()) {
        return null;
    }
    const name = storedName.trim();
    const direct = MATERIAL_TO_PHOSPHOR[name];
    if (direct) {
        return direct;
    }
    const base = stripMaterialStyleSuffix(name);
    const mappedBase = MATERIAL_TO_PHOSPHOR[base];
    if (mappedBase) {
        return mappedBase;
    }
    // Already a Phosphor name (common when library is still MATERIAL/missing after a pick).
    if (PHOSPHOR_ICON_SET.has(name)) {
        return name;
    }
    if (base !== name && PHOSPHOR_ICON_SET.has(base)) {
        return base;
    }
    // Truly unknown Material / legacy names — stable glyph instead of a missing icon.
    return DEFAULT_PHOSPHOR_ICON;
}
